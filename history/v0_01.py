# ساخت config.py
with open('config.py', 'w') as f:
    f.write('''import os
import torch

class Config:
    SEED = 42
    DEVICE = 'cuda' if torch.cuda.is_available() else 'cpu'
    BATCH_SIZE = 4
    IMG_SIZE = (128, 128, 64)
    NUM_WORKERS = 0
    CHECKPOINT_DIR = './checkpoints'
    LOG_DIR = './logs'

    @classmethod
    def setup_dirs(cls):
        os.makedirs(cls.CHECKPOINT_DIR, exist_ok=True)
        os.makedirs(cls.LOG_DIR, exist_ok=True)
''')
print("✅ config.py created!")

# ساخت utils/seed.py
with open('utils/seed.py', 'w') as f:
    f.write('''import random
import numpy as np
import torch

def set_seed(seed: int):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False
''')
print("✅ utils/seed.py created!")

# ساخت data/dataset.py
with open('data/dataset.py', 'w') as f:
    f.write('''import torch
from monai.data import DataLoader
from config import Config

class Synthetic3DDataset(torch.utils.data.Dataset):
    def __init__(self, num_samples=10, img_size=(128,128,64)):
        self.num_samples = num_samples
        self.img_size = img_size

    def __len__(self):
        return self.num_samples

    def __getitem__(self, idx):
        return torch.randn(1, *self.img_size)

def get_dataloader(mode='test', batch_size=4, num_workers=0):
    if mode == 'test':
        dataset = Synthetic3DDataset(num_samples=10, img_size=Config.IMG_SIZE)
        return DataLoader(dataset, batch_size=batch_size, shuffle=False, num_workers=num_workers)
    else:
        raise NotImplementedError("Real data loader not implemented in v0.1")
''')
print("✅ data/dataset.py created!")

# ساخت main.py
with open('main.py', 'w') as f:
    f.write('''import argparse
import torch
from config import Config
from utils.seed import set_seed
from data.dataset import get_dataloader

def test_dataloader():
    print("=== Testing DataLoader ===")
    Config.setup_dirs()
    set_seed(Config.SEED)

    dataloader = get_dataloader(mode='test', batch_size=Config.BATCH_SIZE, num_workers=Config.NUM_WORKERS)

    print(f"Number of batches: {len(dataloader)}")
    for batch_idx, batch in enumerate(dataloader):
        print(f"Batch {batch_idx+1} shape: {batch.shape}")
        if batch_idx == 0:
            print(f"Sample min: {batch.min().item():.4f}, max: {batch.max().item():.4f}")
        break

    print("✅ Test passed! DataLoader works correctly.")

def main():
    parser = argparse.ArgumentParser(description="MedSSL-3D Project")
    parser.add_argument('--mode', type=str, default='test', choices=['test', 'pretrain', 'finetune'])
    args = parser.parse_args()

    if args.mode == 'test':
        test_dataloader()
    else:
        print(f"Mode '{args.mode}' not implemented in v0.1")

if __name__ == '__main__':
    main()
''')
print("✅ main.py created!")

