# 14. اجرای اصلی (Run) — بدون عبور تکراری از Encoder
# ------------------------------------------------------------------------------
def run_v0_3() -> None:
    logger.info("\n" + "=" * 80)
    logger.info("🚀 MedSSL-3D v0.3 FINAL (نسخه‌ی بی‌نقص)")
    logger.info("=" * 80 + "\n")

    Config.setup_dirs()
    set_seed(Config.SEED)
    device = torch.device(Config.DEVICE)
    logger.info(f"💻 Device: {device}\n")

    # ------- دیتاست -------
    dataset = Synthetic3DDataset(num_samples=Config.DATASET_SIZE,
                                 img_size=Config.IMG_SIZE)
    loader = DataLoader(
        dataset,
        batch_size=Config.BATCH_SIZE,
        shuffle=False,
        num_workers=Config.NUM_WORKERS,
        pin_memory=True if device.type == 'cuda' else False
    )
    batch = next(iter(loader))
    logger.info(f"📦 Input batch shape: {batch.shape}")

    # ------- Two‑View Augmentation -------
    aug = TwoViewAugmentation()
    view1, view2 = aug(batch)
    logger.info(f"🔄 View1 shape: {view1.shape}")
    logger.info(f"🔄 View2 shape: {view2.shape}\n")

    # ------- مدل کامل -------
    model = SimCLR3D(
        encoder=resnet18_3d(in_channels=1).to(device),
        projection_dim=Config.PROJECTION_DIM
    ).to(device)

    # نمایش خروجی‌های میانی و نهایی (تنها یک بار عبور از Encoder)
    model.eval()
    with torch.no_grad():
        z1, z2, h1, h2 = model(view1.to(device), view2.to(device),
                               return_features=True)

    logger.info(f"🧠 Encoder output (feature) shape: {h1.shape}")   # (B, 512)
    logger.info(f"🔗 Projection output shape: {z1.shape}")          # (B, 128)

    # ------- یک مرحله آموزش -------
    optimizer = get_optimizer(model, lr=Config.LR)
    logger.info("\n🔄 Running one training iteration ...")
    loss_tensor, loss_value = train_one_iteration(
        model, optimizer, view1, view2, device
    )
    logger.info(f"\n📉 NT-Xent Loss: {loss_value:.4f}")

    # ------- بررسی گرادیان -------
    encoder_grad_exists = any(p.grad is not None for p in model.encoder.parameters())
    logger.info(f"🔄 Backward: {'✅ SUCCESS' if encoder_grad_exists else '❌ FAILED'}")
    logger.info(f"⚙️  Optimizer Step: ✅ SUCCESS (no error)")

    # ------- پیام نهایی -------
    logger.info("\n" + "-" * 40)
    if encoder_grad_exists and loss_value is not None and not torch.isnan(loss_tensor):
        logger.info("✅ SimCLR Pipeline Works Correctly")
    else:
        logger.info("❌ Pipeline encountered an issue. Please review the logs.")

    logger.info("\n📌 Ready for v0.4 (BraTS integration)")
    logger.info("=" * 80 + "\n")

# ------------------------------------------------------------------------------
