# 11. NT‑Xent Loss — پیاده‌سازی استاندارد (مطابق مقاله‌ی SimCLR)
# ------------------------------------------------------------------------------
def nt_xent_loss(z1: torch.Tensor, z2: torch.Tensor,
                 temperature: float = Config.TEMPERATURE) -> torch.Tensor:
    """
    NT‑Xent Loss مطابق مقاله‌ی SimCLR:
        "A Simple Framework for Contrastive Learning of Visual Representations"
        (Chen et al., ICML 2020)
    از torch.logsumexp برای پایداری عددی استفاده شده است.
    """
    batch_size = z1.shape[0]
    device = z1.device

    # نرمال‌سازی بردارها
    z1 = F.normalize(z1, dim=1)
    z2 = F.normalize(z2, dim=1)

    # اجتماع همه‌ی بردارها (۲B, D)
    z = torch.cat([z1, z2], dim=0)

    # ماتریس شباهت (۲B, ۲B)
    sim_matrix = torch.mm(z, z.T) / temperature

    # حذف خود‐شباهت‌ها (قطر اصلی با -inf)
    mask = torch.eye(2 * batch_size, device=device).bool()
    sim_matrix = sim_matrix.masked_fill(mask, -float('inf'))

    # بردار جفت‌های مثبت (اندازه ۲B)
    positive_pairs = torch.cat([
        torch.diag(sim_matrix, diagonal=batch_size),
        torch.diag(sim_matrix, diagonal=-batch_size)
    ], dim=0)

    # محاسبه‌ی logsumexp برای هر سطر (به جز خودش که -inf است)
    log_sum_exp = torch.logsumexp(sim_matrix, dim=1)   # (۲B,)

    # Loss = - (positive - log_sum_exp) به‌طور میانگین
    loss = - (positive_pairs - log_sum_exp).mean()
    return loss

# ------------------------------------------------------------------------------
# 12. Optimizer
# ------------------------------------------------------------------------------
def get_optimizer(model: nn.Module, lr: float = Config.LR) -> optim.Optimizer:
    return optim.Adam(model.parameters(), lr=lr)

# ------------------------------------------------------------------------------
# 13. یک مرحله آموزش (Forward + Loss + Backward + Optimizer Step)
# ------------------------------------------------------------------------------
def train_one_iteration(model: SimCLR3D, optimizer: optim.Optimizer,
                        view1: torch.Tensor, view2: torch.Tensor,
                        device: torch.device) -> Tuple[torch.Tensor, float]:
    model.train()
    view1 = view1.to(device, non_blocking=True)
    view2 = view2.to(device, non_blocking=True)

    optimizer.zero_grad()
    z1, z2 = model(view1, view2)  # فقط خروجی Projection مورد نیاز است
    loss = nt_xent_loss(z1, z2, temperature=Config.TEMPERATURE)
    loss.backward()
    optimizer.step()

    return loss, loss.item()

