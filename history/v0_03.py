# 7. تولید دو نمای متفاوت (Two‑View Augmentation)
# ------------------------------------------------------------------------------
class TwoViewAugmentation:
    """
    تبدیلات سبک و پایدار (بدون MONAI).
    نکته: در v0.4 می‌توانید از MONAI برای افزودن RandomGamma، RandomContrast و
    RandGaussianNoise استفاده کنید تا تنوع بیشتری ایجاد شود.
    """
    def __init__(self, p_flip: float = 0.5, noise_std: float = 0.1,
                 intensity_shift: float = 0.1):
        self.p_flip = p_flip
        self.noise_std = noise_std
        self.intensity_shift = intensity_shift

    def __call__(self, volume: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        vol = volume.clone()

        # نمای اول
        v1 = vol.clone()
        if random.random() < self.p_flip:
            v1 = torch.flip(v1, dims=[3])   # وارونگی در محور depth
        v1 = v1 + torch.randn_like(v1) * self.noise_std
        shift1 = 1.0 + (random.random() - 0.5) * 2 * self.intensity_shift
        v1 = v1 * shift1

        # نمای دوم
        v2 = vol.clone()
        if random.random() < self.p_flip:
            v2 = torch.flip(v2, dims=[2])   # وارونگی در محور width
        v2 = v2 + torch.randn_like(v2) * self.noise_std
        shift2 = 1.0 + (random.random() - 0.5) * 2 * self.intensity_shift
        v2 = v2 * shift2

        return v1, v2

