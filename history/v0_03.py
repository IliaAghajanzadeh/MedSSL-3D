class Synthetic3DDataset(Dataset):
    """دیتاست ساختگی با ۲۰ حجم تصادفی (۱, ۱۲۸, ۱۲۸, ۶۴) - داده‌ها ثابت هستند."""
    def __init__(self, num_samples: int = Config.DATASET_SIZE,
                 img_size: Tuple[int, int, int] = Config.IMG_SIZE):
        self.num_samples = num_samples
        self.img_size = img_size
        # تولید یک‌باره‌ی داده‌ها برای تکرارپذیری کامل
        self.data = [torch.randn(1, *self.img_size, dtype=torch.float32)
                     for _ in range(num_samples)]

    def __len__(self) -> int:
        return self.num_samples

    def __getitem__(self, idx: int) -> torch.Tensor:
        return self.data[idx]

