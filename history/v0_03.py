# 9. Projection Head (۵۱۲ → ۵۱۲ → ۱۲۸)
# ------------------------------------------------------------------------------
class ProjectionHead(nn.Module):
    def __init__(self, input_dim: int = 512, hidden_dim: int = 512,
                 output_dim: int = Config.PROJECTION_DIM):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(input_dim, hidden_dim),
            nn.BatchNorm1d(hidden_dim),
            nn.ReLU(inplace=True),
            nn.Linear(hidden_dim, output_dim)
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.net(x)

# ------------------------------------------------------------------------------
# 10. مدل کامل SimCLR3D (با قابلیت بازگرداندن ویژگی‌های میانی)
# ------------------------------------------------------------------------------
class SimCLR3D(nn.Module):
    """ترکیب Encoder و Projection Head."""
    def __init__(self, encoder: nn.Module, projection_dim: int = Config.PROJECTION_DIM):
        super().__init__()
        self.encoder = encoder
        self.projection = ProjectionHead(input_dim=512, output_dim=projection_dim)

    def forward(self, x1: torch.Tensor, x2: torch.Tensor,
                return_features: bool = False):
        """
        Args:
            x1, x2: دو نمای متفاوت از یک حجم
            return_features: اگر True باشد، علاوه بر خروجی Projection،
                             ویژگی‌های میانی (خروجی Encoder) را نیز بازمی‌گرداند.
        Returns:
            اگر return_features=True: (z1, z2, h1, h2)
            در غیر این صورت: (z1, z2)
        """
        h1 = self.encoder(x1)
        h2 = self.encoder(x2)
        z1 = self.projection(h1)
        z2 = self.projection(h2)

        if return_features:
            return z1, z2, h1, h2
        return z1, z2

    def get_encoder(self) -> nn.Module:
        """دسترسی به Encoder برای v0.5 (Segmentation/Classification Heads)"""
        return self.encoder

